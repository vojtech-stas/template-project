def _render_scope_rules(scope: str, adrs: list[dict]) -> str:
    """
    Render the rule-list body for the given scope + ADRs.

    This is shared between the AREA file renderer and the CLAUDE.md
    region renderer.  Returns the rule-list lines only (no file header,
    no paths: frontmatter — callers add those).
    """
    lines: list[str] = []
    lines.append(f"### {scope.capitalize()} rules\n")
    lines.append(
        f"Atomic rules for the `{scope}` scope, generated from non-superseded ADR "
        f"frontmatter by `tools/gen_rules.py`.\n"
    )
    for adr in adrs:
        adr_id = adr["id"]
        adr_file = adr["path"].name
        lines.append(f"\n#### Source: {adr_id} (`decisions/{adr_file}`)\n")
        for rule_id in adr["rule_ids"]:
            statement = _get_rule_statement(rule_id, adr_id)
            lines.append(f"- **{rule_id}:** {statement}\n")
    return "".join(lines)


def _render_scope(scope: str, adrs: list[dict]) -> str:
    """
    Render .claude/rules/<scope>.md content for an AREA scope.

    AREA files include:
      - The generated-file header comment
      - paths: YAML frontmatter (so Claude Code loads only when relevant)
      - The rule-list body
    """
    paths_val = SCOPE_PATHS.get(scope, "")
    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    # paths: frontmatter line (ADR-0073 D1 — area scopes must declare paths:)
    if paths_val:
        lines.append(f"paths: {paths_val}\n")
    lines.append("\n")
    lines.append(f"# {scope.capitalize()} rules\n")
    lines.append(
        f"Atomic rules for the `{scope}` scope, generated from non-superseded ADR "
        f"frontmatter by `tools/gen_rules.py`.\n"
    )
    for adr in adrs:
        adr_id = adr["id"]
        adr_file = adr["path"].name
        lines.append(f"\n## Source: {adr_id} (`decisions/{adr_file}`)\n")
        for rule_id in adr["rule_ids"]:
            statement = _get_rule_statement(rule_id, adr_id)
            lines.append(f"- **{rule_id}:** {statement}\n")
    return "".join(lines)


def _render_global_file(scopes_adrs: dict[str, list[dict]]) -> str:
    """
    Render all GLOBAL scope rules into .claude/generated/_global.md.

    This single file aggregates all 8 global scopes so CLAUDE.md can
    @import it with one line, keeping CLAUDE.md lean (<200 lines).
    Each scope is rendered as a named section.
    ADR-0073 D1: GLOBAL scopes are always-loaded via the @import mechanism.
    Lives in .claude/generated/ (not .claude/rules/) so the @import is the
    sole load path — no double-load (slice #945).
    """
    lines: list[str] = [GENERATED_HEADER, "\n"]
    lines.append("# Global rules (always-loaded)\n")
    lines.append(
        "All GLOBAL-scope atomic rules, generated from non-superseded ADR frontmatter"
        " by `tools/gen_rules.py`. Loaded into every Claude Code session via the"
        " `@.claude/generated/_global.md` import in CLAUDE.md (ADR-0073 D1)."
        " Lives outside .claude/rules/ so it is not also unconditionally"
        " auto-loaded (slice #945).\n"
    )
    for scope in sorted(scopes_adrs.keys()):
        lines.append("\n")
        lines.append(_render_scope_rules(scope, scopes_adrs[scope]))
    return "".join(lines)


