def _count_rule_ids(scopes: dict[str, list[dict]]) -> int:
    """
    Count the total number of rule_ids across all active scopes.

    Used by --check to report/verify conservation of rule_ids across
    relocation between CLAUDE.md and .claude/rules/ (ADR-0073 D5).
    """
    total = 0
    for scope_adrs in scopes.values():
        for adr in scope_adrs:
            total += len(adr.get("rule_ids", []))
    return total


def generate(check_mode: bool = False) -> int:
    """
    Generate (or diff-check) scope outputs per SCOPE_TARGET classification.

    GLOBAL scopes → .claude/generated/_global.md (@imported by CLAUDE.md;
                    NOT auto-loaded, so the @import is the sole load path).
    AREA scopes   → .claude/rules/<scope>.md (with paths: frontmatter).

    Args:
        check_mode: if True, compare fresh output to committed state and
                    exit non-zero if any differ (mirrors CHECK 2 behavior).
                    Also prints the total rule_id count for conservation checks.

    Returns exit code (0 = success, 1 = failure/dirty).
    """
    adrs = _load_adrs()

    # Separate into active (non-superseded) and superseded
    active_adrs = [a for a in adrs if not _is_superseded(a)]

    if not active_adrs:
        # An empty active-ADR set is never a legitimate no-op in this repo
        # (baseline is RULE_IDS_BASELINE rule_ids across dozens of ADRs) — it
        # is definitionally a broken checkout (missing/unreadable decisions/,
        # or frontmatter that stopped parsing). Fail loud rather than report
        # success while the entire generated-rule layer silently vanishes
        # (#1301).
        print(
            "gen_rules.py: FAIL — zero active ADRs with frontmatter found; "
            "this is treated as a broken checkout (missing/unreadable "
            "decisions/, or frontmatter parse failure), not a valid no-op. "
            "Refusing to leave stale generated output in place (#1301).",
            file=sys.stderr,
        )
        return 1

    # Group by scope
    scopes: dict[str, list[dict]] = {}
    for adr in active_adrs:
        scopes.setdefault(adr["scope"], []).append(adr)

    # Count rule_ids (conservation check — ADR-0073 D5)
    total_rule_ids = _count_rule_ids(scopes)
    print(f"gen_rules.py: total rule_ids across all active scopes: {total_rule_ids}")

    # Ensure .claude/rules/ and .claude/generated/ exist (unless check_mode)
    if not check_mode:
        RULES_DIR.mkdir(parents=True, exist_ok=True)
        GENERATED_DIR.mkdir(parents=True, exist_ok=True)

    any_dirty = False
    generated_files: list[str] = []

    # Collect all GLOBAL scopes for aggregated _global.md rendering
    global_scopes: dict[str, list[dict]] = {
        scope: scope_adrs
        for scope, scope_adrs in sorted(scopes.items())
        if SCOPE_TARGET.get(scope, "area") == "global"
    }

    # --- GLOBAL scopes → .claude/generated/_global.md (single @import target,
    #     NOT auto-loaded — avoids the #945 double-load) ---
    if global_scopes:
        global_content = _render_global_file(global_scopes)

        if check_mode:
            if not GLOBAL_RULES_FILE.exists():
                print(
                    f"DIRTY: {GLOBAL_RULES_FILE.relative_to(REPO_ROOT)} does not exist "
                    f"(run 'python tools/gen_rules.py' and commit)",
                    file=sys.stderr,
                )
                any_dirty = True
            else:
                committed = GLOBAL_RULES_FILE.read_text(encoding="utf-8", errors="replace")
                if committed != global_content:
                    print(
                        f"DIRTY: {GLOBAL_RULES_FILE.relative_to(REPO_ROOT)} differs from "
                        f"fresh gen_rules.py output "
                        f"(run 'python tools/gen_rules.py' and commit)",
                        file=sys.stderr,
                    )
                    any_dirty = True
                else:
                    print(f"CLEAN: {GLOBAL_RULES_FILE.relative_to(REPO_ROOT)}")

            # Also verify CLAUDE.md contains the @import line
            try:
                claude_text = CLAUDE_MD.read_text(encoding="utf-8", errors="replace")
            except OSError:
                claude_text = ""
            if CLAUDE_MD_GLOBAL_IMPORT not in claude_text:
                print(
                    f"DIRTY: CLAUDE.md missing '@import' line '{CLAUDE_MD_GLOBAL_IMPORT}' "
                    f"(run 'python tools/gen_rules.py' and commit)",
                    file=sys.stderr,
                )
                any_dirty = True
            else:
                print(f"CLEAN: CLAUDE.md contains '{CLAUDE_MD_GLOBAL_IMPORT}'")
        else:
            changed = (
                not GLOBAL_RULES_FILE.exists()
                or GLOBAL_RULES_FILE.read_text(encoding="utf-8", errors="replace") != global_content
            )
            if changed:
                GLOBAL_RULES_FILE.write_text(global_content, encoding="utf-8")
                print(f"gen_rules.py: wrote {GLOBAL_RULES_FILE.relative_to(REPO_ROOT)}")
                generated_files.append(str(GLOBAL_RULES_FILE.relative_to(REPO_ROOT)))
            else:
                print(f"gen_rules.py: {GLOBAL_RULES_FILE.relative_to(REPO_ROOT)} already up-to-date")

    # --- AREA scopes → .claude/rules/<scope>.md (path-scoped, one per scope) ---
    for scope, scope_adrs in sorted(scopes.items()):
        if SCOPE_TARGET.get(scope, "area") != "area":
            continue

        content = _render_scope(scope, scope_adrs)
        out_path = RULES_DIR / f"{scope}.md"

        if check_mode:
            # Compare to committed file
            if not out_path.exists():
                print(
                    f"DIRTY: {out_path.relative_to(REPO_ROOT)} does not exist "
                    f"(run 'python tools/gen_rules.py' and commit)",
                    file=sys.stderr,
                )
                any_dirty = True
            else:
                committed = out_path.read_text(encoding="utf-8", errors="replace")
                if committed != content:
                    print(
                        f"DIRTY: {out_path.relative_to(REPO_ROOT)} differs from "
                        f"fresh gen_rules.py output "
                        f"(run 'python tools/gen_rules.py' and commit)",
                        file=sys.stderr,
                    )
                    any_dirty = True
                else:
                    print(f"CLEAN: {out_path.relative_to(REPO_ROOT)}")
        else:
            out_path.write_text(content, encoding="utf-8")
            rel = out_path.relative_to(REPO_ROOT)
            print(f"gen_rules.py: wrote {rel}")
            generated_files.append(str(rel))

    if check_mode:
        # Conservation check: live count must equal the migration baseline (ADR-0073 D5).
        # If it differs, either a new ADR was added (update RULE_IDS_BASELINE) or a rule
        # was silently removed — either way the mismatch is surfaced here.
        if total_rule_ids != RULE_IDS_BASELINE:
            print(
                f"CONSERVATION FAIL: rule_id count {total_rule_ids} != baseline "
                f"{RULE_IDS_BASELINE} — update RULE_IDS_BASELINE in gen_rules.py "
                f"after confirming no rules were lost (ADR-0073 D5)",
                file=sys.stderr,
            )
            any_dirty = True
        else:
            print(
                f"CONSERVATION OK: rule_ids total {total_rule_ids} == "
                f"baseline {RULE_IDS_BASELINE}"
            )
        if not any_dirty:
            print(f"gen_rules.py: all outputs clean (rule_ids total: {total_rule_ids})")
        return 1 if any_dirty else 0

    if not generated_files:
        print("gen_rules.py: nothing to write.", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    check = "--check" in sys.argv
    sys.exit(generate(check_mode=check))
