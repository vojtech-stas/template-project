class TestSetEqualityProofIntegrity(unittest.TestCase):
    """PROOF-INTEGRITY: old rule `pr_number <= 839` grandfathered vs
    grandfathered('PROOF-INTEGRITY', ...). The measured window's left bound
    is #830 (the last grandfathered BROWSER-ROUTE PR under the old rule),
    not #839 itself (#839 is not a merged PR in this repository's history --
    confirmed by the snapshot's own absence of any PR numbered 831-844), so
    the raw PR-number oracle below still holds set equality across the
    full (unfiltered-by-route) merged-PR snapshot."""

    def test_set_equality(self):
        old_set = {n for n, _ in MERGED_PR_SNAPSHOT if n <= 839}
        new_set = {
            n for n, ts in MERGED_PR_SNAPSHOT
            if grandfathered("PROOF-INTEGRITY", ts)
        }
        self.assertEqual(old_set, new_set)

    def test_no_merged_pr_between_830_and_839_exclusive_of_839(self):
        """Precondition the equality above relies on: no merged PR numbered
        831-839 exists, so the #830-anchored instant and the old <=839 rule
        cannot diverge on this snapshot."""
        gap = [n for n, _ in MERGED_PR_SNAPSHOT if 831 <= n <= 839]
        self.assertEqual(gap, [])

    def test_instant_in_measured_window(self):
        # Window: [#830 2026-06-16T10:46:59Z, #845 2026-06-16T16:00:26Z)
        instant = GRANDFATHER_UNTIL["PROOF-INTEGRITY"]
        self.assertGreaterEqual(instant, "2026-06-16T10:46:59Z")
        self.assertLess(instant, "2026-06-16T16:00:26Z")


